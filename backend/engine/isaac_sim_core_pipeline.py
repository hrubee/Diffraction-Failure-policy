    if os.path.exists(args.robot_usd):
        robot = world.scene.add(
            Robot(
                prim_path="/World/Robot",
                name="client_manipulator",
                usd_path=args.robot_usd,
                position=np.array([0.0, 0.0, 0.75]),
            )
        )
    else:
        print(f"[WARN] Robot USD not found at {{args.robot_usd}}, using reference prim")
